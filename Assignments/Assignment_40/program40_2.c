#include <stdio.h>

////////////////////////////////////////////////////////////////
//
//  Function Name:  Display
//  Description:    It is used to display numbers with '*' 
//                  in decreasing order using recursion.
//  Input:          void
//  Output:         void
//  Author:         Sakshi Ravindra Darandale
//  Date:           08/02/2026
//
////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    if(iNo > 0)
    {
        printf("%d\t *\t",iNo);
        iNo--;
        Display(iNo);
    }
}

////////////////////////////////////////////////////////////////
//
//  Entry point function
//
////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the number : ");
    scanf("%d",&iValue);

    Display(iValue);
    
    return 0;
}

