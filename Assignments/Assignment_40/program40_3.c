#include <stdio.h>

////////////////////////////////////////////////////////////////
//
//  Function Name:  Display
//  Description:    It is used to display numbers from 5 to 1
//                  using recursion.
//  Input:          int
//  Output:         void
//  Author:         Sakshi Ravindra Darandale
//  Date:           08/02/2026
//
////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    
    if(iNo>=1)
    {
        printf("%d\t",iNo);
        iNo--;
        Display(iNo);
    }
}

////////////////////////////////////////////////////////////////
//
//  Entry point function
//
////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the number : ");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}

