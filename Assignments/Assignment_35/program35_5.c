#include <stdio.h>

////////////////////////////////////////////////////////////////
//
//  Function Name:  ReverseDisplay
//  Description:    It is used to display the given string in reverse
//                  order
//  Input:          char* 
//  Output:         void 
//  Author:         Sakshi Ravindra Darandale
//  Date:           27/11/2025
//
////////////////////////////////////////////////////////////////

void ReverseDisplay(char str[])
{
    char *temp = str;
    while(*str != '\0')
    {
        str++;
    }
    
    while(str >= temp)
    {
        printf("%c", *str);
        str--;
    }
}

////////////////////////////////////////////////////////////////
//
//  Entry point function
//
////////////////////////////////////////////////////////////////

int main()
{
    char Arr[50] = {'\0'};
    
    printf("Enter the string : ");
    scanf("%[^'\n']s", Arr);
    
    ReverseDisplay(Arr);

    return 0;
}

