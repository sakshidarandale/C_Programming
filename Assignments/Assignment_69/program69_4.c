#include <stdio.h>

////////////////////////////////////////////////////////////////
//
//  Function Name:  Display
//  Description:    It is used to display numbers from A to F
//                  using recursion.
//  Input:          int
//  Output:         void
//  Author:         Sakshi Ravindra Darandale
//  Date:           08/02/2026
//
////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    if(iNo > 0)
    {
        Display(iNo - 1);
        printf("%c\t", 'A' + iNo - 1);
    }
}

////////////////////////////////////////////////////////////////
//
//  Entry point function
//
////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the number : ");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}

