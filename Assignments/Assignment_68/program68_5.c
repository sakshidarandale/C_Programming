#include <stdio.h>

////////////////////////////////////////////////////////////////
//
//  Function Name:  Display
//  Description:    It is used to display numbers from a to f
//                  using recursion.
//  Input:          int,int,char
//  Output:         void
//  Author:         Sakshi Ravindra Darandale
//  Date:           08/02/2026
//
////////////////////////////////////////////////////////////////

void Display(int iNo,int iCnt,char ch)
{

    if(iCnt<=iNo)
    {
        printf("%c\t",ch);
        ch++;
        iCnt++;

        Display(iNo,iCnt,ch);
    }
}

////////////////////////////////////////////////////////////////
//
//  Entry point function
//
////////////////////////////////////////////////////////////////

int main()
{
    Display(6,1,'a');

    return 0;
}

