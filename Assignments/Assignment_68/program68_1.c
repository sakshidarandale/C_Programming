#include <stdio.h>

////////////////////////////////////////////////////////////////
//
//  Function Name:  Display
//  Description:    It is used to display '*'  using
//                  recursion and static variable
//  Input:          void
//  Output:         void
//  Author:         Sakshi Ravindra Darandale
//  Date:           08/02/2026
//
////////////////////////////////////////////////////////////////

void Display()
{
    static int i = 1;

    if(i<=5)
    {
        printf("*\t");
        i++;

        Display();
    }
}

////////////////////////////////////////////////////////////////
//
//  Entry point function
//
////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

