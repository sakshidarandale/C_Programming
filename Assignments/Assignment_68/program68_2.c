#include <stdio.h>

////////////////////////////////////////////////////////////////
//
//  Function Name:  Display
//  Description:    It is used to display numbers from 1 to 5
//                  using recursion.
//  Input:          int
//  Output:         void
//  Author:         Sakshi Ravindra Darandale
//  Date:           08/02/2026
//
////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    if(iNo<=5)
    {
        printf("%d\t",iNo);
        iNo++;
        Display(iNo);
    }
}

////////////////////////////////////////////////////////////////
//
//  Entry point function
//
////////////////////////////////////////////////////////////////

int main()
{
    Display(1);

    return 0;
}

